"""Emit a C header with int8 weights / requant params for c/spike_edge.c,
and binary I/O helpers for the host harness."""
import subprocess
from pathlib import Path

import numpy as np

from . import WIN
from .qnn import ARCHS, layer_shapes

ROOT = Path(__file__).resolve().parents[1]
CDIR = ROOT / "c"


def _arr(ctype, name, a):
    vals = ", ".join(str(int(v)) for v in np.asarray(a).ravel())
    return f"static const {ctype} {name}[{np.asarray(a).size}] = {{{vals}}};\n"


def header(arch_name, q):
    arch = ARCHS[arch_name]
    shp = layer_shapes(arch, WIN)
    s = [f"/* generated by spike_edge/export_c.py for {arch_name}; do not edit */\n",
         '#include "spike_edge.h"\n']
    descs = []
    assert max(co * lo for (_, _, co, lo) in shp) <= 128, "raise SE_MAX_ACT in c/spike_edge.c"
    for i, (L, (typ, co, k, st), (ci, li, co_, lo)) in enumerate(zip(q, arch, shp)):
        s.append(_arr("int8_t", f"w{i}", L["w"]))
        s.append(_arr("int32_t", f"b{i}", L["b"]))
        if "m" in L:
            s.append(_arr("int32_t", f"m{i}", L["m"]))
            s.append(_arr("int32_t", f"sh{i}", L["sh"]))
            mm = f"m{i}, sh{i}"
        else:
            mm = "0, 0"
        t = "SE_CONV" if typ == "conv" else "SE_DENSE"
        lin = li if typ == "conv" else ci          # dense: flattened input length
        descs.append(f"  {{{t}, {ci}, {co}, {k}, {st}, {lin}, {lo}, w{i}, b{i}, {mm}}}")
    s.append("static const se_layer_t se_layers[] = {\n" + ",\n".join(descs) + "\n};\n")
    s.append(f"static const se_model_t SE_MODEL = {{se_layers, {len(q)}}};\n")
    return "".join(s)


def header_path(arch_name):
    return CDIR / "generated" / f"model_{arch_name}.h"


def write_header(arch_name, q):
    p = header_path(arch_name)
    p.parent.mkdir(exist_ok=True)
    p.write_text(header(arch_name, q))
    return p


def build(arch_name, opt="-O2"):
    """Host harness against the committed header. SE_CFLAGS (env) adds flags, e.g.
    '-fsanitize=undefined -fno-sanitize-recover=all' in CI."""
    import os
    out = ROOT / "build" / f"harness_{arch_name}"
    out.parent.mkdir(exist_ok=True)
    extra = os.environ.get("SE_CFLAGS", "").split()
    subprocess.run(["cc", "-std=c99", opt, "-Wall", "-Wextra", "-Werror", *extra, f"-I{CDIR}", f"-I{CDIR/'generated'}",
                    f'-DMODEL_HEADER="model_{arch_name}.h"', str(CDIR / "harness.c"), str(CDIR / "spike_edge.c"),
                    "-o", str(out)], check=True)
    return out


def run_harness(exe, raw, gate_thr, gain, logit_thr, workdir, no_model=False, start=0):
    workdir = Path(workdir); workdir.mkdir(parents=True, exist_ok=True)
    fin, fout = workdir / "in.bin", workdir / "out.bin"
    with open(fin, "wb") as f:
        np.array([len(raw), gate_thr, gain, logit_thr], np.int32).tofile(f)
        raw.astype(np.int16).tofile(f)
    cmd = [str(exe), str(fin), str(fout)] + (["--no-model"] if no_model else []) + ["--start", str(start)]
    subprocess.run(cmd, check=True, capture_output=True)
    b = fout.read_bytes()
    n = len(raw)
    y = np.frombuffer(b[: 2 * n], np.int16)
    n_ev = int(np.frombuffer(b[2 * n: 2 * n + 4], np.int32)[0])
    ev = np.frombuffer(b[2 * n + 4:], np.int32).reshape(n_ev, 3).astype(np.int64)
    ev[:, 0] = (ev[:, 0] - start) % (1 << 32)   # back to stream-relative indices
    return y, ev
